$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot 'Test-ContextSecrets.ps1')
$taskRoot=Join-Path ([IO.Path]::GetTempPath()) ('agent-vault-scanner-'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $taskRoot | Out-Null
$taskNeedle=[Guid]::NewGuid().ToString('N')+'"\'+'测试'
$taskPatterns=New-SecretPatterns @($taskNeedle)
function Assert-Scan([string]$Name,[string]$Content,[string]$Expected){
    $taskFile=Join-Path $taskRoot $Name
    [IO.File]::WriteAllText($taskFile,$Content,[Text.UTF8Encoding]::new($false))
    $taskResult=Invoke-ContextSecretScan @($taskFile) $taskPatterns
    if($taskResult.conclusion -ne $Expected){throw 'Scanner regression failed'}
}
Assert-Scan 'clear.request.json' '{"messages":[{"content":"ordinary business result"}]}' 'NO_MATCH_IN_SCANNED_TEXT'
$taskEncoded=ConvertTo-Json -InputObject @{messages=@(@{content=$taskNeedle})} -Depth 5 -Compress
Assert-Scan 'leak.request.json' $taskEncoded 'MATCH_FOUND'
$taskUnicode='"'+(($taskNeedle.ToCharArray()|ForEach-Object{'\u{0:x4}' -f [int]$_}) -join '')+'"'
Assert-Scan 'unicode.request.json' ('{"content":'+$taskUnicode+'}') 'MATCH_FOUND'
$taskBase64=[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($taskNeedle))
Assert-Scan 'base64.request.json' ('{"content":"'+$taskBase64+'"}') 'MATCH_FOUND'
Assert-Scan 'private.request.json' '{"content":"-----BEGIN OPENSSH PRIVATE KEY-----"}' 'MATCH_FOUND'
Assert-Scan 'invalid.request.json' '{invalid' 'INCOMPLETE'
$taskMissing=Invoke-ContextSecretScan @((Join-Path $taskRoot 'absent')) $taskPatterns
if($taskMissing.conclusion -ne 'INCOMPLETE'){throw 'Missing evidence was incorrectly accepted'}
Write-Output 'Context scanner: 7 regression checks passed; no test values printed.'
# Only explicitly named files generated by this test are removed.
Get-ChildItem -LiteralPath $taskRoot -File | Remove-Item -Force
Remove-Item -LiteralPath $taskRoot
